import { mkdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = fileURLToPath(new URL("../", import.meta.url));
const publicRoot = path.join(root, "public");
const sources = new Set();
for (const file of ["app/page.tsx", "lib/catalog-data.ts", "app/quem-somos/page.tsx"]) {
  const source = await readFile(path.join(root, file), "utf8");
  for (const match of source.matchAll(/"(\/(?:partners\/|method-|field\/|catalog\/covers\/|about-)[^"\s]+\.webp)"/g)) {
    sources.add(match[1]);
  }
}

const manifest = {};
let variants = 0;
for (const src of [...sources].sort()) {
  const input = path.join(publicRoot, src);
  const metadata = await sharp(input).metadata();
  if (!metadata.width || !metadata.height || metadata.orientation) {
    throw new Error(`Expected an already oriented image: ${src}`);
  }
  const originalBytes = (await stat(input)).size;
  const candidates = [];
  for (const width of [320, 480, 640, 960, 1280]) {
    if (width >= metadata.width) continue;
    // Resize the full frame. CSS remains responsible for the existing crop.
    const buffer = await sharp(input)
      .resize({ width, withoutEnlargement: true })
      .webp({ quality: 92, effort: 6 })
      .toBuffer();
    // A responsive alternative must save bytes over the unchanged original.
    if (buffer.length >= originalBytes) continue;
    const url = `/responsive${src.replace(/\.webp$/, `-${width}.webp`)}`;
    const output = path.join(publicRoot, url);
    await mkdir(path.dirname(output), { recursive: true });
    await writeFile(output, buffer);
    candidates.push(`${url} ${width}w`);
    variants++;
  }
  if (candidates.length) {
    candidates.push(`${src} ${metadata.width}w`);
    manifest[src] = candidates.join(", ");
  }
}

await writeFile(path.join(root, "lib/responsive-images-data.ts"),
  "// Generated by scripts/generate-responsive-images.mjs. Originals remain unchanged.\n" +
  "export const responsiveImageSources: Record<string, string> = " +
  JSON.stringify(manifest, null, 2) + ";\n");
console.log(JSON.stringify({ images: Object.keys(manifest).length, variants }));
